// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Кнопка-іконка без імені, знайдена статично (ACCESSIBILITY-v9 § 10.6,
 * `A11Y-STATIC-ICON-LABEL`).
 *
 * ## Чому не досить axe
 *
 * `tests/a11y.spec.ts` міряє те, що на екрані після `goto()` — і міряє добре:
 * дев'ять сторінок, чотири теми, три стилі, відкриті меню. Але кнопка в модалці,
 * у гілці `{#if}` або в стані помилки в той знімок не потрапляє **ніколи**, а
 * саме там кнопки-іконки й живуть: закрити, скинути, спробувати ще раз.
 *
 * Тут навпаки — розмітка читається як текст, тож видно **всі** гілки одразу, і
 * не видно нічого про те, як воно виглядає. Дві перевірки не заміняють одна
 * одну, і канон просить обидві.
 *
 * ## Що саме вважається іменем
 *
 * Текст усередині, `aria-label` або `aria-labelledby`. Вставка `{вираз}`
 * рахується текстом: вона ставить символи на екран, а чи ті це символи —
 * питання не до розмітки. `{#if}`, `{/if}`, `{:else}`, `{@const}` не рахуються:
 * це керування, а не вміст.
 *
 * ## Ім'я — зі словника, а не літералом
 *
 * Другий інваріант нижче. Літерал `aria-label="Закрити"` проходить перший
 * інваріант і лишає кнопку без імені в трьох мовах із чотирьох — тобто гейт
 * зелений саме там, де дефект. Заміряно на HEAD: усіх 25 імен у проєкті
 * приходять із `t()`, `tFormat()`, `pick()` або пропа, тож інваріант описує
 * наявну практику, а не вводить нову.
 *
 * ## Зворотний експеримент
 *
 * Проведено: кнопка з одним `<X />` усередині й без `aria-label` — названий
 * файл із рядком; `aria-label="Close"` літералом — названий той самий рядок
 * другим інваріантом.
 */

const ROOT = resolve(__dirname, '..');

function компоненти(dir = 'src', out: string[] = []): string[] {
	for (const entry of readdirSync(resolve(ROOT, dir), { withFileTypes: true })) {
		const path = `${dir}/${entry.name}`;
		if (entry.isDirectory()) компоненти(path, out);
		else if (entry.name.endsWith('.svelte')) out.push(path);
	}
	return out;
}

/**
 * Гасить коментарі й тіла `<script>`/`<style>`, зберігаючи кількість рядків.
 *
 * Без цього слово `<button>` у прозі докблока читається як розмітка: у
 * `Minimap.svelte` саме такий коментар і зупиняв першу редакцію розбору.
 */
const погасити = (текст: string) =>
	текст
		.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '))
		.replace(/<script[\s\S]*?<\/script>/g, (m) => m.replace(/[^\n]/g, ' '))
		.replace(/<style[\s\S]*?<\/style>/g, (m) => m.replace(/[^\n]/g, ' '));

/**
 * Кінець відкривного тега — перший `>` поза лапками й поза `{…}`.
 *
 * Наївний `[^>]*>` обривається на стрілці `=>` в `onclick={() => …}`, а таких
 * атрибутів тут більшість: перша редакція розбору через це бачила половину
 * атрибутів кнопки як її вміст і давала десять хибних знахідок.
 */
function кінецьТега(текст: string, від: number): number {
	let рівень = 0;
	let лапка = '';
	for (let i = від; i < текст.length; i++) {
		const c = текст[i];
		if (лапка) {
			if (c === лапка) лапка = '';
			continue;
		}
		if (c === '"' || c === "'") лапка = c;
		else if (c === '{') рівень++;
		else if (c === '}') рівень--;
		else if (c === '>' && рівень === 0) return i;
	}
	return -1;
}

/** Парний закривний тег, з урахуванням вкладеності однойменних. */
function кінецьЕлемента(текст: string, від: number, тег: string): number {
	const відкрив = new RegExp(`<${тег}\\b`, 'g');
	const закрив = new RegExp(`</${тег}\\s*>`, 'g');
	let рівень = 0;
	let i = від;
	while (i < текст.length) {
		відкрив.lastIndex = i;
		закрив.lastIndex = i;
		const o = відкрив.exec(текст);
		const c = закрив.exec(текст);
		if (!c) return -1;
		if (o && o.index < c.index) {
			рівень++;
			i = o.index + 1;
		} else {
			рівень--;
			if (рівень === 0) return c.index;
			i = c.index + 1;
		}
	}
	return -1;
}

/**
 * Чи прочитає читалка з цієї розмітки хоч щось.
 *
 * Крім тексту й вставок, ім'я дає непорожній `alt` картинки всередині: обгортка
 * `<a><img alt="…"></a>` — головний спосіб зробити логотип посиланням, і в
 * `OrgLogos.svelte` таких чотирнадцять. Порожній `alt=""` навпаки — обіцянка,
 * що картинка декоративна, тож імені з неї немає.
 */
function маєТекст(вміст: string): boolean {
	if (/\balt\s*=\s*(?:"[^"]+"|'[^']+'|\{)/.test(вміст)) return true;
	const без = вміст
		.replace(/\{[#/:]\s*[\s\S]*?\}/g, ' ')
		.replace(/\{@(const|debug)\b[\s\S]*?\}/g, ' ')
		.replace(/<\/?[A-Za-z][^>]*>/g, ' ');
	return /\{[^}]*\}/.test(без) || /\S/.test(без.replace(/\{[^}]*\}/g, ' '));
}

type Кнопка = { файл: string; рядок: number; атрибути: string; вміст: string };

function кнопки(файл: string, текст: string, тег: 'button' | 'a'): Кнопка[] {
	const знайдені: Кнопка[] = [];
	let i = 0;
	for (;;) {
		const початок = текст.indexOf(`<${тег}`, i);
		if (початок === -1) break;
		i = початок + тег.length + 1;
		// `<a` не сміє зловити `<article`: після назви тега має бути пробіл або `>`.
		if (!/[\s>]/.test(текст[початок + тег.length + 1] ?? '')) continue;
		const кінецьВідкрив = кінецьТега(текст, початок);
		const кінецьВмісту = кінецьЕлемента(текст, початок, тег);
		if (кінецьВідкрив === -1 || кінецьВмісту === -1) continue;
		знайдені.push({
			файл,
			рядок: текст.slice(0, початок).split('\n').length,
			атрибути: текст.slice(початок + тег.length + 1, кінецьВідкрив),
			вміст: текст.slice(кінецьВідкрив + 1, кінецьВмісту)
		});
	}
	return знайдені;
}

const усі = компоненти().flatMap((файл) => {
	const текст = погасити(readFileSync(resolve(ROOT, файл), 'utf8'));
	return [...кнопки(файл, текст, 'button'), ...кнопки(файл, текст, 'a')];
});

const названа = ({ атрибути }: Кнопка) => /\baria-label(ledby)?\b/.test(атрибути);

describe('§ 10.6 — кнопка-іконка без імені', () => {
	it('перевірка жива: кнопки й посилання знайдено', () => {
		// Розбір, що не знаходить нічого, дає нуль знахідок і читається як чистий
		// проєкт — той самий клас, що й порожній граф імпортів у structure.test.ts.
		expect(усі.length, 'жодної кнопки чи посилання — розбір зламався').toBeGreaterThan(20);
		expect(
			усі.filter(названа).length,
			'жодного aria-label — розбір атрибутів зламався'
		).toBeGreaterThan(5);
	});

	it('кожна кнопка й кожне посилання мають ім’я', () => {
		const безімені = усі
			.filter((к) => !названа(к) && !маєТекст(к.вміст))
			.map((к) => `${к.файл}:${к.рядок}`);

		expect(
			безімені,
			`ні тексту, ні aria-label — читалка прочитає порожнє:\n${безімені.join('\n')}`
		).toEqual([]);
	});

	it('ім’я приходить зі словника, а не літералом у розмітці', () => {
		// `aria-label="Закрити"` — це кнопка без імені в трьох мовах із чотирьох, і
		// перший інваріант її пропускає. Ознака — відсутність `{` у значенні: усе,
		// що йде зі словника, приходить виразом.
		const літерали: string[] = [];
		for (const к of усі) {
			for (const m of к.атрибути.matchAll(/\baria-label\s*=\s*"([^"]*)"/g)) {
				if (!m[1].includes('{')) літерали.push(`${к.файл}:${к.рядок} — aria-label="${m[1]}"`);
			}
		}
		expect(
			літерали,
			`ім’я вписане рядком: у решті мов кнопка лишиться без нього:\n${літерали.join('\n')}`
		).toEqual([]);
	});
});
