/**
 * Читання розмітки `.svelte` як тексту — спільна частина статичних гейтів.
 *
 * Гейти, які дивляться в розмітку, а не в браузер, ловлять те, чого не видно
 * інакше: гілку `{#if}`, у яку жоден `goto()` не заходить, кнопку в модалці,
 * атрибут, якого немає. Ціна — власний розбір, а розбір Svelte має рівно одну
 * пастку, і на ній спіткнулася кожна перша редакція:
 *
 * ```svelte
 * <img src={withBase(LOCALE_OPTIONS.find((l) => l.id === locale)!.flags[0])} width={W} />
 * ```
 *
 * Наївний `<img[^>]*>` обривається на `>` у стрілці `(l) =>`, тобто бачить тег
 * без половини атрибутів. Далі це не помилка розбору, а **хибний висновок**:
 * гейт «кожна картинка має `width`» назве цей рядок порушенням, хоча `width`
 * там є. Гейт, який видає хибні знахідки на правильному коді, вимикають першим.
 *
 * Функції нижче жили копією в `a11y-static.test.ts` і мали переїхати сюди тієї
 * ж миті, коли знадобилися вдруге: дві копії розбору — це два місця, де пастку
 * треба знати, і одне, де її забудуть.
 *
 * Модуль не імпортує жоден компонент і в бандл не потрапляє: його читають лише
 * перевірки. Досяжним його робить саме це — `structure.test.ts` вважає файли
 * перевірок точками входу.
 */

/**
 * Гасить коментарі й тіла `<script>`/`<style>`, зберігаючи кількість рядків.
 *
 * Без цього слово `<button>` у прозі докблока читається як розмітка: у
 * `Minimap.svelte` саме такий коментар і зупиняв першу редакцію розбору.
 * Заміна на пробіли, а не викидання, щоб номери рядків у звіті лишалися
 * номерами рядків у файлі.
 */
export const blankNonMarkup = (text: string): string =>
	text
		.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '))
		.replace(/<script[\s\S]*?<\/script>/g, (m) => m.replace(/[^\n]/g, ' '))
		.replace(/<style[\s\S]*?<\/style>/g, (m) => m.replace(/[^\n]/g, ' '));

/**
 * Кінець відкривного тега — перший `>` поза лапками й поза `{…}`.
 *
 * Саме та пастка, про яку докблок модуля: без урахування `{…}` розбір
 * обривається на стрілці `=>` в будь-якому атрибуті-виразі.
 *
 * @param text розмітка (бажано вже після `blankNonMarkup`)
 * @param from індекс `<` початку тега
 * @returns індекс `>` або -1, якщо тег не закритий
 */
export function tagEnd(text: string, from: number): number {
	let depth = 0;
	let quote = '';
	for (let i = from; i < text.length; i++) {
		const c = text[i];
		if (quote) {
			if (c === quote) quote = '';
			continue;
		}
		if (c === '"' || c === "'") quote = c;
		else if (c === '{') depth++;
		else if (c === '}') depth--;
		else if (c === '>' && depth === 0) return i;
	}
	return -1;
}

/**
 * Кожен відкривний тег `name` у розмітці, цілим рядком від `<` до `>`.
 *
 * @param text розмітка (бажано вже після `blankNonMarkup`)
 * @param name ім'я тега, наприклад `img`
 */
export function openingTags(text: string, name: string): string[] {
	const out: string[] = [];
	const start = new RegExp(`<${name}\\b`, 'g');
	for (let m = start.exec(text); m; m = start.exec(text)) {
		const end = tagEnd(text, m.index);
		if (end === -1) break;
		out.push(text.slice(m.index, end + 1));
		start.lastIndex = end;
	}
	return out;
}
