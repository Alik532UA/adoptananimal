// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';

/**
 * Світла тема оголошує `only light` — і ніде не оголошує голе `light`.
 *
 * ## Що це стереже
 *
 * Android Chrome із темною темою САМОГО браузера має Auto Dark Theme: він
 * перемальовує в темні кольори кожну сторінку, яку вважає світлою й без
 * власної темної теми. Ознака, за якою він це вирішує, — використана схема
 * документа, і саме голе `color-scheme: light` її й оголошує. Відмова
 * називається `only`.
 *
 * Заміряно на пристрої в сусідньому `teatralo4ka.odesa.ua` 7 вересня 2026:
 * автор надіслав знімок, де світлі теми сайту перефарбовані до невпізнання, а
 * після заміни на `only light` перемальовування зникло на тому самому телефоні.
 * Правило — UI-UX-v9 `UIUX-ONLY-LIGHT`.
 *
 * ## Чому кілька джерел, а не одне
 *
 * Схему присвоюють у кількох місцях: таблиця стилів, мета-тег у розмітці,
 * скрипт першого кадру й контролер теми. У школі гейт дивився лише на
 * `app.html` і був ЗЕЛЕНИЙ увесь час, поки скрипт рядком нижче переписував
 * значення на `light`. Тому перевірка читає всі джерела, де схема може
 * зʼявитися — включно з файлами тем, які до 2026-09-10 не казали нічого.
 *
 * **CSS сильніший за мета-тег.** Поки теми мовчали, використану схему брав
 * мета-тег — тобто вона існувала рівно доти, доки виконувався скрипт, і на
 * першому кадрі, до нього, документ оголошував `light dark`. На телефоні з
 * темним браузером це означає використану схему `dark` на світлій сторінці:
 * нативні смуги прокрутки, поля вводу й автозаповнення малюються темними
 * (UI-UX-v9 § 1.5.1.2, реальний випадок із темою `colorful`).
 *
 * ## Зворотний експеримент
 *
 * Проведено тричі: `only light` повернено до `light` — перевірка назвала файл
 * із номером рядка; `color-scheme` прибрано з `winter.css` — названо тему без
 * оголошення; `dark` в `orange-purple.css` замінено на `only light` — названо
 * розбіжність зі світлістю власного тла.
 */
const ТЕМИ_ТЕКА = 'src/lib/styles/themes';
const РОЗМІТКА = 'src/app.html';
const КОНТРОЛЕР = 'src/lib/services/settings.svelte.ts';

const читати = (ф: string) => readFileSync(ф, 'utf8');

const файлиТем = readdirSync(ТЕМИ_ТЕКА)
	.filter((назва) => назва.endsWith('.css'))
	.sort();

const ДЖЕРЕЛА = [РОЗМІТКА, КОНТРОЛЕР, ...файлиТем.map((назва) => `${ТЕМИ_ТЕКА}/${назва}`)];

/**
 * Чи темна тема — рахується з її власного тла, а не з ще одного списку назв.
 *
 * Список назв тут був би четвертою копією того самого факту, і саме такі копії
 * розходяться мовчки: `orange-purple` темна за тлом (#1a0f2e) і світла за
 * назвою, тож будь-хто, хто напише список з голови, помилиться саме на ній.
 * Відносна яскравість за WCAG, поріг посередині — теми цього проєкту лежать
 * далеко від нього з обох боків (0.01 і 0.02 проти 0.89 і 0.92).
 */
function яскравістьТла(css: string): number {
	const hex = /--color-bg:\s*#([0-9a-f]{6})\b/i.exec(css)?.[1];
	if (!hex) return NaN;
	const канал = (пара: string) => {
		const c = parseInt(пара, 16) / 255;
		return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
	};
	return (
		0.2126 * канал(hex.slice(0, 2)) +
		0.7152 * канал(hex.slice(2, 4)) +
		0.0722 * канал(hex.slice(4, 6))
	);
}

describe('color-scheme світлої теми', () => {
	it('перевірка жива: джерела прочитано й схема в них є', () => {
		const усе = ДЖЕРЕЛА.map(читати).join('|');
		expect(файлиТем.length, 'файлів тем не знайдено — тека переїхала').toBeGreaterThan(2);
		expect(усе.length, 'джерела порожні').toBeGreaterThan(100);
		expect(усе, 'жодного оголошення color-scheme — стерегти нема чого').toContain('color-scheme');
	});

	it('ніде немає голого `light`: ні в CSS, ні в мета-тезі, ні в скрипті', () => {
		const bad: string[] = [];
		for (const ф of ДЖЕРЕЛА) {
			читати(ф)
				.split('\n')
				.forEach((рядок, i) => {
					// Рядок, що ПРИСВОЮЄ схему: властивість CSS або значення мета-тега.
					const присвоєння = /color-scheme\s*:|colorScheme\s*=|name="color-scheme"/.test(рядок);
					if (!присвоєння) return;
					if (/(:|=)\s*["']?\s*light\s*["']?\s*;?\s*$|content="light"/.test(рядок)) {
						bad.push(`${ф}:${i + 1} — ${рядок.trim()}`);
					}
				});
		}
		expect(bad, `Auto Dark Theme перемалює світлу тему:\n${bad.join('\n')}`).toEqual([]);
	});

	it('кожна тема оголошує схему в CSS, і рівно раз', () => {
		// Тема, яка мовчить, віддає використану схему системній перевазі гостя, а не
		// власній природі. «Рівно раз» — бо друге оголошення в тому самому файлі це
		// два джерела одного значення, і розходяться вони в один бік із чотирьох.
		const порушення = файлиТем
			.map((назва) => {
				const скільки = (читати(`${ТЕМИ_ТЕКА}/${назва}`).match(/^\s*color-scheme\s*:/gm) ?? [])
					.length;
				return { назва, скільки };
			})
			.filter(({ скільки }) => скільки !== 1)
			.map(({ назва, скільки }) => `${назва}: ${скільки}`);

		expect(
			порушення,
			`очікується рівно одне оголошення color-scheme на тему:\n${порушення.join('\n')}`
		).toEqual([]);
	});

	it('схема теми відповідає світлості її власного тла', () => {
		const порушення: string[] = [];
		for (const назва of файлиТем) {
			const css = читати(`${ТЕМИ_ТЕКА}/${назва}`);
			const яскравість = яскравістьТла(css);
			expect(яскравість, `${назва}: --color-bg не читається як #rrggbb`).not.toBeNaN();

			const схема = /^\s*color-scheme\s*:\s*([^;]+);/m.exec(css)?.[1].trim();
			const очікувана = яскравість < 0.5 ? 'dark' : 'only light';
			if (схема !== очікувана) {
				порушення.push(
					`${назва}: тло дає яскравість ${яскравість.toFixed(2)}, тобто «${очікувана}», а стоїть «${схема}»`
				);
			}
		}
		expect(порушення, `схема розійшлася з палітрою:\n${порушення.join('\n')}`).toEqual([]);
	});

	it('перелік темних тем у CSS, у скрипті першого кадру й у контролері — один', () => {
		/*
		 * Той самий факт лежить у трьох місцях, і жодне з них не може імпортувати два
		 * інші: скрипт першого кадру не імпортує нічого за визначенням, а CSS не
		 * імпортує взагалі. UI-UX-v9 § 1.1 називає таку дубльовану умову боргом і
		 * просить звіряти її інваріантом — ось він.
		 */
		const заCSS = файлиТем
			.filter((назва) => /^\s*color-scheme\s*:\s*dark\s*;/m.test(читати(`${ТЕМИ_ТЕКА}/${назва}`)))
			.map((назва) => назва.replace(/\.css$/, ''))
			.sort();

		const заРозміткою = (/const DARK_SCHEMES = \[([^\]]+)\]/.exec(читати(РОЗМІТКА))?.[1] ?? '')
			.split(',')
			.map((s) => s.trim().replace(/^['"]|['"]$/g, ''))
			.filter(Boolean)
			.sort();

		// `this.theme === 'dark' || this.theme === 'orange-purple'` — перелік як він
		// написаний у контролері, зібраний з порівнянь у тому самому виразі.
		const рядокКонтролера = /const темна =([^;]+);/.exec(читати(КОНТРОЛЕР))?.[1] ?? '';
		const заКонтролером = [...рядокКонтролера.matchAll(/'([^']+)'/g)].map((m) => m[1]).sort();

		expect(заCSS.length, 'у CSS немає жодної темної теми — розбір зламався').toBeGreaterThan(0);
		expect(заРозміткою, 'DARK_SCHEMES в app.html розійшовся з файлами тем').toEqual(заCSS);
		expect(заКонтролером, 'перелік у settings.svelte.ts розійшовся з файлами тем').toEqual(заCSS);
	});
});
