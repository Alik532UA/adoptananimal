// @vitest-environment node
import { describe, expect, it } from 'vitest';

import config from '../svelte.config.js';

/**
 * Відкрита до деплою вкладка переживає деплой (VERSIONING-v9 § 4.5,
 * `VER-OPEN-TAB-SURVIVES`, HIGH) — і тримає це не наш код, а рантайм SvelteKit.
 *
 * ## Що саме описує правило
 *
 * Кожна збірка перейменовує чанки за хешем вмісту. Вкладка, відкрита ДО
 * деплою, тримає в пам'яті старий перелік адрес: перший перехід тягне
 * `_app/immutable/nodes/3.Dxzs2ghZ.js`, отримує 404, і сторінка, яка щойно
 * працювала, віддає «Internal Error».
 *
 * ## Заміряно, а не вичитано
 *
 * `PROJECT-CONTEXT.md` півмісяця тримав це відкритим питанням і міркував, як
 * таку поведінку написати самому — перепит версії, повне завантаження при
 * переході, запасний шар у `handleError`, маркер у `sessionStorage` проти
 * циклу. Виявилося, що писати нічого не треба.
 *
 * Експеримент 2026-09-11, дві справжні збірки (усі хеші чанків різні,
 * `_app/version.json` різний) і статичний сервер, якому на льоту підмінили
 * каталог під відкритою вкладкою. Порядок запитів після підміни:
 *
 * ```
 * 404 /_app/immutable/nodes/3.Dxzs2ghZ.js   ← вкладка просить чанк старої збірки
 * 200 /_app/version.json                    ← client.js питає, чи це новий деплой
 * 200 /adopt/cat                            ← повне завантаження, а не помилка
 * 200 …/nodes/3.BE56SBoT.js                 ← чанк уже нової збірки
 * ```
 *
 * Читач опинився на робочій сторінці `Adopt a Cat`. Ніякого «Internal Error»,
 * жодного циклу: після перезавантаження вкладка тримає нову версію, тож
 * повторитися нема з чого. Механізм — `stores.updated.check()` у
 * `@sveltejs/kit/src/runtime/client/client.js`: він викликається САМЕ в місці
 * збою, тому опитування за таймером (§ 4.1) для цієї половини правила не
 * потрібне.
 *
 * ## Що тоді стереже цей файл
 *
 * Дві речі, кожна з яких вимикає весь механізм мовчки — сторінка й далі
 * виглядатиме справною, доки хтось не оновить сайт із відкритою вкладкою.
 *
 * **1. Штамп версії має мінятися з кожною ЗБІРКОЮ.** Типово SvelteKit ставить
 * час збірки, і це те, на чому все тримається. Поширений рецепт
 * `version: { name: pkg.version }` виглядає охайніше й ламає рівно це: між
 * двома деплоями однієї версії пакета `updated.check()` каже «та сама версія»,
 * і рантайм замість повного завантаження малює помилку. Тут `version` не
 * задано взагалі, і саме це фіксує інваріант.
 *
 * **2. `_app/version.json` має лежати в `build/`.** Без нього перепит версії —
 * це 404, `check()` повертає `false`, і знову помилка замість перезавантаження.
 * Цю половину стереже `check-build.js` § 4E, а не цей файл: наявність файлу у
 * `build/` — властивість ВИВОДУ, і юніт-тест мусив би або вимагати збірки, або
 * мовчки пропускати себе без неї. Пропуск гірший за відсутність: прогін
 * зеленіє, нічого не перевіривши.
 *
 * ## Чого тут навмисно немає
 *
 * Заборони `skipWaiting()` в service worker (§ 4.5, третій пункт): service
 * worker'а в проєкті немає жодного, тож інваріанту не було б на чому впасти —
 * а гейт над відсутнім кодом читається як зроблена робота.
 *
 * ## Зворотний експеримент
 *
 * Проведено: дописав `version: { name: '1' }` у `kit` — червоніє інваріант
 * нижче; перейменував `build/_app/version.json` — червоніє `check-build` § 4E.
 */

describe('відкрита вкладка переживає деплой (§ 4.5)', () => {
	it('штамп версії не прибитий до релізу — він має мінятися з кожною збіркою', () => {
		expect(
			config.kit?.version?.name,
			'задане `name` робить штамп сталим у межах релізу, і тоді updated.check() ' +
				'каже «та сама версія» на чужих чанках — замість перезавантаження читач ' +
				'бачить Internal Error'
		).toBeUndefined();
	});
});
